import os.path
from qgis.PyQt.QtCore import QCoreApplication, QLocale, QTranslator
from qgis.PyQt.QtGui import QIcon
from qgis.PyQt.QtWidgets import QAction, QFileDialog
from qgis.core import QgsProject, QgsSettings, QgsVectorFileWriter
from qgis.gui import QgsMessageBar

# Import the code for the dialog
from .save_dxf_dialog import SaveDxfDialog


class SaveDxf:
    """QGIS Plugin Implementation."""

    def __init__(self, iface):
        """Constructor.

        :param iface: An interface instance that will be passed to this class
            which provides the hook by which you can manipulate the QGIS
            application at run time.
        :type iface: QgsInterface
        """
        # Save reference to the QGIS interface
        self.iface = iface
        # initialize plugin directory
        self.plugin_dir = os.path.dirname(__file__)
        # initialize locale
        locale = QgsSettings().value(
            "locale/userLocale", QLocale().name()
        )[0:2]
        locale_path = os.path.join(
            self.plugin_dir, "i18n", "{}.qm".format(locale)
        )

        if os.path.exists(locale_path):
            self.translator = QTranslator()
            self.translator.load(locale_path)
            QCoreApplication.installTranslator(self.translator)

        # Declare instance attributes
        self.actions = []
        self.menu = self.tr("&Save DXF")

        # Check if plugin was started the first time in current QGIS session
        # Must be set in initGui() to survive plugin reloads
        self.first_start = None

    # noinspection PyMethodMayBeStatic
    def tr(self, message):
        """Get the translation for a string using Qt translation API.

        We implement this ourselves since we do not inherit QObject.

        :param message: String for translation.
        :type message: str, QString

        :returns: Translated version of message.
        :rtype: QString
        """
        # noinspection PyTypeChecker,PyArgumentList,PyCallByClass
        return QCoreApplication.translate("SaveDxf", message)

    def add_action(
        self,
        icon_path,
        text,
        callback,
        enabled_flag=True,
        add_to_menu=True,
        add_to_toolbar=True,
        status_tip=None,
        whats_this=None,
        parent=None,
    ):
        """Add a toolbar icon to the toolbar."""

        icon = QIcon(icon_path)
        action = QAction(icon, text, parent)
        action.triggered.connect(callback)
        action.setEnabled(enabled_flag)

        if status_tip is not None:
            action.setStatusTip(status_tip)

        if whats_this is not None:
            action.setWhatsThis(whats_this)

        if add_to_toolbar:
            # Adds plugin icon to Plugins toolbar
            self.iface.addToolBarIcon(action)

        if add_to_menu:
            self.iface.addPluginToVectorMenu(self.menu, action)

        self.actions.append(action)

        return action

    def initGui(self):
        """Create the menu entries and toolbar icons inside the QGIS GUI."""

        icon_path = os.path.join(os.path.dirname(__file__), "icon.png")
        self.add_action(
            icon_path,
            text=self.tr("Convert to dxf"),
            callback=self.run,
            parent=self.iface.mainWindow(),
        )

        # will be set False in run()
        self.first_start = True

    def unload(self):
        """Removes the plugin menu item and icon from QGIS GUI."""
        for action in self.actions:
            self.iface.removePluginVectorMenu(self.tr("&Save DXF"), action)
            self.iface.removeToolBarIcon(action)

    # --- HELPER METHOD FOR BROWSE BUTTON ---
    def select_output_file(self):
        """Opens a file dialog when Browse... is clicked."""
        filename, _ = QFileDialog.getSaveFileName(
            self.dlg, "Select Output DXF File", "", "DXF Files (*.dxf)"
        )
        if filename:
            self.dlg.output_path.setText(filename)

    def run(self):
        """Run method that performs all the real work"""

        # Create the dialog with elements (after translation) and keep reference
        # Only create GUI ONCE in callback, so that it will only load when the plugin is started
        if self.first_start == True:
            self.first_start = False
            self.dlg = SaveDxfDialog()

            # Connect custom push buttons
            self.dlg.browse_button.clicked.connect(self.select_output_file)
            self.dlg.ok_button.clicked.connect(self.dlg.accept)
            self.dlg.cancel_button.clicked.connect(self.dlg.reject)

        self.dlg.layer_combo.clear()
        layers = QgsProject.instance().layerTreeRoot().children()
        self.dlg.layer_combo.addItems([layer.name() for layer in layers])

        # show the dialog
        self.dlg.show()
        # Run the dialog event loop
        result = self.dlg.exec_()

        # See if OK was pressed
        if result:
            filename = self.dlg.output_path.text()
            selectedLayerIndex = self.dlg.layer_combo.currentIndex()
            selectedLayer = layers[selectedLayerIndex].layer()
            QgsVectorFileWriter.writeAsVectorFormat(
                selectedLayer,
                filename,
                "utf-8",
                selectedLayer.crs(),
                "DXF",
                skipAttributeCreation=True,
            )
            self.iface.messageBar().pushSuccess(
                "Saved", "Output file: " + filename
            )
            pass